export function creditCardLabel(v) {
  if (v === 'no') return 'Без карты';
  if (v === 'phone') return 'Телефон';
  if (v === 'paid') return 'Платный';
  if (v === 'none') return 'Без ключа';
  return 'Регистрация';
}

export function matchProvider(baseUrl, providerId) {
  if (providerId) {
    const byId = AI_PROVIDERS.find((p) => p.id === providerId);
    if (byId) return byId;
  }
  const n = String(baseUrl || '').trim().replace(/\/+$/, '').toLowerCase();
  if (!n) return null;
  for (const p of AI_PROVIDERS) {
    if (!p.baseUrl) continue;
    const pb = p.baseUrl.replace(/\/+$/, '').toLowerCase();
    if (n === pb || n.startsWith(pb) || pb.startsWith(n)) return p;
  }
  return null;
}
